//! Checks of a compiled binary against the font document.

use std::collections::hash_map::Entry;
use std::collections::{BTreeMap, HashMap, HashSet};

use forma_model::{Font, KernRef};
use read_fonts::tables::cmap::CmapIterLimits;
use read_fonts::types::{GlyphId, Tag};
use read_fonts::{FontRef, TableProvider};

use crate::model_checks::exported_glyphs;
use crate::{Finding, Severity, sort_findings};

/// The tables every font FORMA produces must have.
const REQUIRED_TABLES: [Tag; 10] = [
    Tag::new(b"cmap"),
    Tag::new(b"head"),
    Tag::new(b"hhea"),
    Tag::new(b"hmtx"),
    Tag::new(b"maxp"),
    Tag::new(b"name"),
    Tag::new(b"OS/2"),
    Tag::new(b"post"),
    Tag::new(b"glyf"),
    Tag::new(b"loca"),
];

/// The glyph that must be glyph 0.
const NOTDEF: &str = ".notdef";

const TABLES: &str = "binary.tables";
const CMAP: &str = "binary.cmap";
const HMTX: &str = "binary.hmtx";
const NOTDEF_CHECK: &str = "binary.notdef";
const GPOS: &str = "binary.gpos";

/// Checks the compiled TrueType font `binary` against `font`, reporting every
/// difference as an error. The findings are sorted like those of a report.
///
/// `font` must be the font as the compiler saw it, that is the result of
/// [`forma_compile::preflight`]: the compiler adds a `.notdef` and a `space`
/// glyph that the edited model may lack, and the binary is expected to hold
/// them. Only exported glyphs are expected in the binary. The checks are:
///
/// - `binary.tables`: the tables `cmap head hhea hmtx maxp name OS/2 post glyf
///   loca` are present; the glyph names can be read from `post`; every
///   exported glyph is in the binary under its name, and the binary has no
///   other glyph;
/// - `binary.cmap`: the `cmap` maps exactly the code points of the exported
///   glyphs, each to its own glyph (glyphs are matched by name, through
///   `post`);
/// - `binary.hmtx`: the advance width of each glyph is the advance width of
///   its default master layer, rounded with [`f64::round`];
/// - `binary.notdef`: glyph 0 is `.notdef`.
///
/// - `binary.gpos`: when the model has kerning that reaches the binary (a pair
///   of the default master whose sides are exported glyphs, or groups with an
///   exported member), the `GPOS` table is present.
///
/// A font whose `.notdef` is not exported gets one generated by the compiler,
/// whose advance width the model knows nothing about, so only its position is
/// checked. Problems with one table do not stop the checks that do not need
/// it, but the checks that match glyphs by name need a readable `post`.
#[must_use]
pub fn check_binary(font: &Font, binary: &[u8]) -> Vec<Finding> {
    let mut findings = Vec::new();
    let compiled = match FontRef::new(binary) {
        Ok(compiled) => compiled,
        Err(error) => {
            findings.push(error_finding(
                TABLES,
                None,
                format!("the compiled font cannot be read: {error}"),
            ));
            return findings;
        }
    };

    for tag in REQUIRED_TABLES {
        if compiled.table_data(tag).is_none() {
            findings.push(error_finding(
                TABLES,
                None,
                format!("the {tag} table is missing"),
            ));
        }
    }

    // Everything below matches glyphs by name, and `post` has the names.
    if let Some(names) = glyph_names(&compiled, &mut findings) {
        let ids = glyph_ids(&names, &mut findings);
        check_glyph_set(font, &names, &ids, &mut findings);
        check_notdef(&names, &mut findings);
        check_cmap(font, &compiled, &names, &mut findings);
        check_hmtx(font, &compiled, &ids, &mut findings);
    }
    check_gpos(font, &compiled, &mut findings);

    sort_findings(&mut findings);
    findings
}

fn error_finding(check: &str, glyph: Option<&str>, message: String) -> Finding {
    Finding::new(check, Severity::Error, glyph, message)
}

/// The glyph names of the binary, by glyph id, from `post`. Reports and
/// returns `None` if they cannot be had; a missing `post` or `maxp` has been
/// reported already.
fn glyph_names(compiled: &FontRef, findings: &mut Vec<Finding>) -> Option<Vec<String>> {
    compiled.table_data(Tag::new(b"post"))?;
    compiled.table_data(Tag::new(b"maxp"))?;
    let (post, maxp) = match (compiled.post(), compiled.maxp()) {
        (Ok(post), Ok(maxp)) => (post, maxp),
        (Err(error), _) | (_, Err(error)) => {
            findings.push(error_finding(
                TABLES,
                None,
                format!("the glyph names cannot be read: {error}"),
            ));
            return None;
        }
    };
    let names: Vec<String> = post
        .glyph_names()
        .map(|(_, name)| name.to_owned())
        .collect();
    let glyphs = usize::from(maxp.num_glyphs());
    if names.len() != glyphs {
        findings.push(error_finding(
            TABLES,
            None,
            format!(
                "the post table names {} of the {glyphs} glyphs of the font, \
                 so glyphs cannot be told apart",
                names.len()
            ),
        ));
        return None;
    }
    Some(names)
}

/// The glyph ids by name. A name that occurs twice is reported and keeps its
/// first glyph id.
fn glyph_ids<'a>(names: &'a [String], findings: &mut Vec<Finding>) -> HashMap<&'a str, u32> {
    let mut ids: HashMap<&str, u32> = HashMap::new();
    for (gid, name) in (0..).zip(names) {
        match ids.entry(name) {
            Entry::Vacant(slot) => {
                slot.insert(gid);
            }
            Entry::Occupied(first) => findings.push(error_finding(
                TABLES,
                Some(name),
                format!("the name is used by glyph {} and glyph {gid}", first.get()),
            )),
        }
    }
    ids
}

/// Every exported glyph is in the binary, and nothing else is. Glyph 0 is
/// left to [`check_notdef`].
fn check_glyph_set(
    font: &Font,
    names: &[String],
    ids: &HashMap<&str, u32>,
    findings: &mut Vec<Finding>,
) {
    let expected: HashSet<&str> = exported_glyphs(font)
        .map(|glyph| glyph.name.as_str())
        .collect();
    for glyph in exported_glyphs(font).filter(|glyph| glyph.name != NOTDEF) {
        if !ids.contains_key(glyph.name.as_str()) {
            findings.push(error_finding(
                TABLES,
                Some(&glyph.name),
                "the glyph is exported by the model but missing from the compiled font".to_owned(),
            ));
        }
    }
    for name in names.iter().skip(1) {
        if !expected.contains(name.as_str()) {
            findings.push(error_finding(
                TABLES,
                Some(name),
                "the glyph is in the compiled font but not exported by the model".to_owned(),
            ));
        }
    }
}

/// Glyph 0 is `.notdef`.
fn check_notdef(names: &[String], findings: &mut Vec<Finding>) {
    match names.first() {
        None => findings.push(error_finding(
            NOTDEF_CHECK,
            None,
            "the compiled font has no glyphs; glyph 0 must be .notdef".to_owned(),
        )),
        Some(name) if name != NOTDEF => findings.push(error_finding(
            NOTDEF_CHECK,
            Some(name),
            format!("glyph 0 is {name:?}; it must be {NOTDEF:?}"),
        )),
        Some(_) => {}
    }
}

/// The `cmap` maps the code points of the exported glyphs, each to its glyph,
/// and nothing else.
fn check_cmap(font: &Font, compiled: &FontRef, names: &[String], findings: &mut Vec<Finding>) {
    if compiled.table_data(Tag::new(b"cmap")).is_none() {
        return; // reported already
    }
    let cmap = match compiled.cmap() {
        Ok(cmap) => cmap,
        Err(error) => {
            findings.push(error_finding(
                CMAP,
                None,
                format!("the cmap table cannot be read: {error}"),
            ));
            return;
        }
    };

    let expected: BTreeMap<u32, &str> = exported_glyphs(font)
        .flat_map(|glyph| {
            glyph
                .unicodes
                .iter()
                .map(|&codepoint| (codepoint, glyph.name.as_str()))
        })
        .collect();
    // The subtable a text engine would pick. Mapping a code point to glyph 0
    // is the same as not mapping it (and format 4 ends with such a segment
    // for U+FFFF), so those entries are left out.
    let actual: BTreeMap<u32, u32> = cmap
        .best_subtable()
        .map(|(_, _, subtable)| {
            subtable
                .iter_with_limits(CmapIterLimits::default_for_font(compiled))
                .map(|(codepoint, gid)| (codepoint, gid.to_u32()))
                .filter(|&(_, gid)| gid != 0)
                .collect()
        })
        .unwrap_or_default();
    let name_of = |gid: u32| usize::try_from(gid).ok().and_then(|gid| names.get(gid));

    for (&codepoint, &glyph) in &expected {
        match actual.get(&codepoint) {
            None => findings.push(error_finding(
                CMAP,
                Some(glyph),
                format!("U+{codepoint:04X} is not mapped, but the model encodes it in this glyph"),
            )),
            Some(&gid) if name_of(gid).map(String::as_str) != Some(glyph) => {
                let found = name_of(gid).map_or_else(
                    || format!("glyph {gid}, which has no name"),
                    |name| format!("{name:?} (glyph {gid})"),
                );
                findings.push(error_finding(
                    CMAP,
                    Some(glyph),
                    format!(
                        "U+{codepoint:04X} is mapped to {found}, \
                         but the model encodes it in this glyph"
                    ),
                ));
            }
            Some(_) => {}
        }
    }
    for (&codepoint, &gid) in &actual {
        if !expected.contains_key(&codepoint) {
            findings.push(error_finding(
                CMAP,
                name_of(gid).map(String::as_str),
                format!(
                    "U+{codepoint:04X} is mapped to glyph {gid}, but the model does not encode it"
                ),
            ));
        }
    }
}

/// The advance width of each glyph is the model's, rounded.
fn check_hmtx(
    font: &Font,
    compiled: &FontRef,
    ids: &HashMap<&str, u32>,
    findings: &mut Vec<Finding>,
) {
    if compiled.table_data(Tag::new(b"hmtx")).is_none() {
        return; // reported already
    }
    let hmtx = match compiled.hmtx() {
        Ok(hmtx) => hmtx,
        Err(error) => {
            findings.push(error_finding(
                HMTX,
                None,
                format!("the hmtx table cannot be read: {error}"),
            ));
            return;
        }
    };
    let Some(master) = font.masters.first().map(|master| master.id) else {
        return;
    };

    for glyph in exported_glyphs(font) {
        // A glyph that is not in the binary has been reported already, and a
        // glyph without a default layer is not something to compare.
        let (Some(&gid), Some(layer)) = (ids.get(glyph.name.as_str()), glyph.layers.get(&master))
        else {
            continue;
        };
        let expected = layer.advance_width.round();
        match hmtx.advance(GlyphId::new(gid)) {
            Some(advance) if f64::from(advance) == expected => {}
            Some(advance) => findings.push(error_finding(
                HMTX,
                Some(&glyph.name),
                format!(
                    "the advance width is {advance} in hmtx, but the model has {} \
                     (rounded to {expected})",
                    layer.advance_width
                ),
            )),
            None => findings.push(error_finding(
                HMTX,
                Some(&glyph.name),
                format!("hmtx has no advance width for glyph {gid}"),
            )),
        }
    }
}

/// Kerning in the model needs a `GPOS` table in the binary. Pairs that the
/// export leaves out (they use glyphs that are not exported) do not count, and
/// only the default master is compiled.
fn check_gpos(font: &Font, compiled: &FontRef, findings: &mut Vec<Finding>) {
    if compiled.table_data(Tag::new(b"GPOS")).is_some() {
        return;
    }
    let Some(master) = font.masters.first().map(|master| master.id) else {
        return;
    };
    let Some(pairs) = font.kerning.pairs.get(&master) else {
        return;
    };
    let exported = |reference: KernRef| match reference {
        KernRef::Glyph(id) => font
            .glyphs
            .get(&id)
            .is_some_and(|glyph| glyph.is_exported()),
        KernRef::Group(id) => font.kerning.groups.get(&id).is_some_and(|group| {
            group
                .members
                .iter()
                .any(|id| font.glyphs.get(id).is_some_and(|glyph| glyph.is_exported()))
        }),
    };
    let count = pairs
        .keys()
        .filter(|&&(first, second)| exported(first) && exported(second))
        .count();
    if count > 0 {
        findings.push(error_finding(
            GPOS,
            None,
            format!(
                "the model has {count} kerning pair(s) but the compiled font has no GPOS table"
            ),
        ));
    }
}
